def write_all():
    banned = ["—", "без крови", "ведущ", "золотой стандарт", "не откладывайте", "сотни и тысячи", "за 1 посещение", "в карточке"]
    for doc in DOCTORS:
        folder = ROOT / str(doc["id"])
        folder.mkdir(parents=True, exist_ok=True)
        files = {
            "activity.html": doc["activity"],
            "education.html": lists(doc["education"], style=True),
        }
        if "awards_blocks" in doc:
            files["awards.html"] = lists([], blocks=doc["awards_blocks"])
        else:
            files["awards.html"] = lists(doc["awards"])
        if "conferences_blocks" in doc:
            files["conferences.html"] = lists([], blocks=doc["conferences_blocks"])
        elif "conferences" in doc:
            files["conferences.html"] = lists(doc["conferences"], tail=doc.get("conferences_tail", ""))
        blob = "\n".join(files.values())
        for word in banned:
            if word in blob:
                raise SystemExit("banned %r in %s" % (word, doc["id"]))
        for name, html in files.items():
            (folder / name).write_text(html, encoding="utf-8")
        print(doc["id"], " ".join(files))


if __name__ == "__main__":
    write_all()

