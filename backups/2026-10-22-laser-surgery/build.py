def lists(items, style=False, blocks=None, tail=""):
    parts = [STYLE] if style else []
    if blocks is None:
        blocks = [("", items)]
    chunks = []
    for title, rows in blocks:
        head = ""
        if title:
            head = '\t<h3 style="font-size: 20px; color: #008080; margin: 8px 0 12px;">%s</h3>\n' % title
        lis = "\n".join("\t\t<li>%s</li>" % row for row in rows)
